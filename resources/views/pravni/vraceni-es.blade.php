<h1>Política de reembolso</h1>
<p>En vigor desde el 30 de octubre de 2026</p>

<p>
    Nuestro proceso de pedidos lo gestiona nuestro revendedor en línea <strong>Paddle.com</strong> (Paddle.com Market Limited).
    Paddle.com es el comerciante registrado (Merchant of Record) de todos nuestros pedidos, por lo que los reembolsos los gestiona Paddle conforme a su
    <a href="https://www.paddle.com/legal/refund-policy" target="_blank" rel="noopener">política de reembolso</a>.
    El servicio lo presta WormUP s.r.o. (véanse los <a href="{{ \App\Support\Domeny::url('web', '/terms') }}">Términos y condiciones</a>).
</p>

<h2>Cómo solicitar un reembolso</h2>
<ul>
    <li>Presente su solicitud en un plazo de 14 días desde el pago en <a href="https://paddle.net" target="_blank" rel="noopener">paddle.net</a>
        o mediante el enlace del correo electrónico con su recibo.</li>
    <li>Paddle examina cada solicitud de forma individual. Rechaza los reembolsos en caso de fraude o abuso.</li>
</ul>

<h2>Derecho de desistimiento del consumidor</h2>
<p>
    Los consumidores de la UE (y de otros países cuya legislación lo prevea) tienen derecho a desistir de un contrato
    celebrado a distancia en un plazo de 14 días. Este derecho no se aplica a los pagos posteriores de una suscripción en curso.
    Los casos en que se pierde el derecho de desistimiento (por ejemplo, cuando el servicio comenzó de inmediato a petición expresa suya) se
    indican en la política de reembolso de Paddle.
</p>

<h2>Cancelación de la suscripción</h2>
<p>
    Puede cancelar su suscripción en cualquier momento en la aplicación (Suscripción). La cancelación surte efecto al final
    del periodo pagado: hasta entonces, el plan sigue activo y no se cobra ningún otro pago. La cancelación por sí sola no da
    derecho al reembolso del resto del periodo.
</p>

<h2>Consultas</h2>
<p>
