<h2>3. Pliki cookie</h2>
<p>
    <strong>Niezbędne pliki cookie</strong> stosujemy zawsze: do logowania (sesja), ochrony formularzy (CSRF),
    zapamiętania wybranego języka i zapisania wyboru dokonanego w banerze cookies (<code>tt_cookies</code>, 12 miesięcy).
</p>
<p>
    <strong>Analityczne pliki cookie</strong> (Google Analytics 4: <code>_ga</code>, <code>_ga_*</code>, ważność
    do 2 lat) zapisujemy tylko za zgodą wyrażoną w banerze cookies. Służą do pomiaru ruchu — jakie strony
    i funkcje są używane, skąd przyszedł odwiedzający, jakie ma urządzenie i przeglądarkę oraz jaka jest jego przybliżona lokalizacja.
    Google Analytics nie przechowuje adresu IP. Dane przetwarza Google (Google Ireland Ltd., ewentualnie Google LLC
    w USA) i przechowuje je przez 14 miesięcy; my widzimy je tylko w zbiorczych zestawieniach. Bez zgody do Google
    nie jest wysyłane nic.
</p>
<p>
    <strong>Marketingowe pliki cookie</strong> (pomiar skuteczności reklam) również tylko za zgodą; obecnie
    ich nie stosujemy — gdy je wprowadzimy, zastosowanie będzie miał wybór dokonany wcześniej w banerze.
</p>
<p>
    Zgodę można w każdej chwili zmienić lub wycofać za pomocą linku „Ustawienia cookies” w stopce strony; wycofanie
    nie wpływa na zgodność z prawem wcześniejszego przetwarzania. Podstawa prawna: zgoda (art. 6 ust. 1 lit. a RODO
    i § 89 ust. 3 czeskiej ustawy nr 127/2005 Sb. o łączności elektronicznej).
</p>

