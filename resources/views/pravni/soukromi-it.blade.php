<h2>3. Cookie</h2>
<p>
    I <strong>cookie necessari</strong> sono sempre utilizzati: per l’accesso (sessione), la protezione dei moduli (CSRF),
    la memorizzazione della lingua scelta e della scelta espressa nel banner dei cookie (<code>tt_cookies</code>, 12 mesi).
</p>
<p>
    I <strong>cookie analitici</strong> (Google Analytics 4: <code>_ga</code>, <code>_ga_*</code>, validi fino a
    2 anni) vengono memorizzati solo con il consenso dell’utente prestato nel banner dei cookie. Misurano il traffico: quali
    pagine e funzioni vengono utilizzate, la provenienza della visita, il tipo di dispositivo e browser e la posizione approssimativa.
    Google Analytics non memorizza gli indirizzi IP. I dati sono trattati da Google (Google Ireland Ltd. o
    Google LLC negli Stati Uniti) e conservati per 14 mesi; noi vediamo solo report aggregati. Senza consenso, a Google
    non viene inviato nulla.
</p>
<p>
    Anche i <strong>cookie di marketing</strong> (misurazione della pubblicità) sono utilizzati solo con il consenso; al momento
    non li utilizziamo: quando li introdurremo, varrà la scelta espressa nel banner.
</p>
<p>
    Il consenso può essere modificato o revocato in qualsiasi momento tramite il link “Impostazioni cookie” nel piè di pagina del sito;
    la revoca non pregiudica la liceità del trattamento precedente. Base giuridica: il consenso dell’utente (art. 6, par. 1, lett. a)
    GDPR e art. 89, comma 3, della legge ceca n. 127/2005 Racc. sulle comunicazioni elettroniche).
</p>

