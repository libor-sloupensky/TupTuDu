<h2>3. Cookies</h2>
<p>
    Les <strong>cookies essentiels</strong> sont toujours utilisés : pour la connexion (session), la protection des formulaires (CSRF),
    la mémorisation de la langue choisie et l’enregistrement de votre choix dans le bandeau cookies (<code>tt_cookies</code>, 12 mois).
</p>
<p>
    Les <strong>cookies analytiques</strong> (Google Analytics 4 : <code>_ga</code>, <code>_ga_*</code>, valables
    jusqu’à 2 ans) ne sont déposés qu’avec votre consentement donné dans le bandeau cookies. Ils mesurent l’audience : les
    pages et fonctionnalités que vous utilisez, votre provenance, votre type d’appareil et de navigateur et votre localisation approximative.
    Google Analytics ne conserve pas les adresses IP. Les données sont traitées par Google (Google Ireland Ltd. ou
    Google LLC aux États-Unis) et conservées 14 mois ; nous ne voyons que des rapports agrégés. Sans consentement, rien
    n’est transmis à Google.
</p>
<p>
    Les <strong>cookies marketing</strong> (mesure publicitaire) ne sont eux aussi utilisés qu’avec votre consentement ; nous ne les utilisons
    pas pour le moment. Lorsque nous les introduirons, le choix que vous avez fait dans le bandeau s’appliquera.
</p>
<p>
    Vous pouvez modifier ou retirer votre consentement à tout moment via le lien « Paramètres des cookies » en bas de page du site ;
    le retrait n’affecte pas la licéité du traitement antérieur. Base juridique : votre consentement (art. 6, par. 1, point a) du
    RGPD et article 89, paragraphe 3, de la loi tchèque n° 127/2005 Sb. sur les communications électroniques).
</p>

