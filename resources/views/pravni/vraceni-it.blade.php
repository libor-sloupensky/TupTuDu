<h2>Come richiedere un rimborso</h2>
<ul>
    <li>La richiesta va presentata entro 14 giorni dal pagamento su <a href="https://paddle.net" target="_blank" rel="noopener">paddle.net</a>
        oppure tramite il link nell’email con la ricevuta di pagamento.</li>
    <li>Paddle valuta ogni richiesta singolarmente. Rifiuta il rimborso in caso di frode o abuso.</li>
</ul>

<h2>Diritto di recesso del consumatore</h2>
<p>
    I consumatori nell’UE (e negli altri Paesi in cui la legge lo prevede) hanno il diritto di recedere da un
    contratto a distanza entro 14 giorni. Tale diritto non si applica ai pagamenti successivi di un abbonamento già in corso.
    I casi in cui il diritto di recesso si estingue (ad esempio quando il servizio è iniziato immediatamente su espressa richiesta del consumatore) sono
    indicati nella politica di rimborso di Paddle.
</p>

<h2>Annullamento dell’abbonamento</h2>
<p>
    L’abbonamento può essere annullato in qualsiasi momento nell’applicazione (Abbonamento). L’annullamento ha effetto alla fine
    del periodo pagato: fino ad allora il piano resta attivo e non viene addebitato alcun ulteriore pagamento. L’annullamento in sé non
    comporta il rimborso della parte restante del periodo.
</p>

