<h2>2. Co služba nabízí</h2>
<p>
    TupTuDu je online nástroj pro vytváření konceptu stavby nebo rekonstrukce — dispozice, půdorysu
    a jeho prostorového zobrazení (dále „projekt“). Služba je určena především soukromým osobám, které
    plánují stavbu nebo rekonstrukci, a také firmám a projektantům, kteří v ní připravují koncept pro své klienty.
</p>
<p>
    <strong>Projekt vytvořený ve službě je orientační koncept.</strong> Nenahrazuje projektovou dokumentaci
    vyžadovanou právními předpisy, statický výpočet ani posouzení oprávněným odborníkem (architektem,
    projektantem, statikem). Před stavbou nebo povolovacím řízením je vždy potřeba projekt nechat zpracovat
    a ověřit odborníkem podle předpisů země, kde se stavba nachází.
</p>
<p>
    Údaje z veřejných a externích zdrojů (např. katastrální a mapové podklady, výškopis nebo geologická data
    státních úřadů a dalších poskytovatelů) služba přebírá tak, jak je zdroj poskytuje, a mají informativní
    charakter. Jejich rozsah se liší podle země. Provozovatel neodpovídá za jejich správnost, úplnost ani aktuálnost.
</p>

