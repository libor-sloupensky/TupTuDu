<h2>3. Cookies</h2>
<p>
    <strong>Nevyhnutné cookies</strong> používame vždy: na prihlásenie (relácia), ochranu formulárov (CSRF),
    zapamätanie zvoleného jazyka a uloženie vašej voľby v lište cookies (<code>tt_cookies</code>, 12 mesiacov).
</p>
<p>
    <strong>Analytické cookies</strong> (Google Analytics 4: <code>_ga</code>, <code>_ga_*</code>, platnosť
    až 2 roky) ukladáme len s vaším súhlasom udeleným v lište cookies. Slúžia na meranie návštevnosti — ktoré
    stránky a funkcie používate, odkiaľ ste prišli, aké máte zariadenie a prehliadač a približnú polohu.
    Google Analytics IP adresu neukladá. Údaje spracúva Google (Google Ireland Ltd., prípadne Google LLC
    v USA) a uchováva ich 14 mesiacov; my ich vidíme len v súhrnných prehľadoch. Bez súhlasu sa do Googlu
    neodosiela nič.
</p>
<p>
    <strong>Marketingové cookies</strong> (meranie účinnosti reklamy) rovnako len so súhlasom; v súčasnosti
    ich nepoužívame — keď ich zavedieme, uplatní sa voľba, ktorú ste urobili v lište.
</p>
<p>
    Súhlas môžete kedykoľvek zmeniť alebo odvolať odkazom „Nastavenia cookies“ v pätičke webu; odvolanie
    nemá vplyv na zákonnosť skoršieho spracúvania. Právny základ: váš súhlas (čl. 6 ods. 1 písm. a GDPR
    a § 89 ods. 3 českého zákona č. 127/2005 Sb., o elektronických komunikáciách).
</p>

