<h1>Vrácení peněz</h1>
<p>Účinné od: 30. 10. 2026</p>

<p>
    Placené tarify služby TupTuDu prodává náš online prodejce <strong>Paddle.com</strong> (Paddle.com Market Limited),
    který je obchodníkem (Merchant of Record) pro všechny naše objednávky. Vrácení peněz proto vyřizuje Paddle
    podle svých <a href="https://www.paddle.com/legal/refund-policy" target="_blank" rel="noopener">pravidel pro vrácení peněz</a>.
    Provozovatelem služby je WormUP s.r.o. (viz <a href="{{ \App\Support\Domeny::url('web', '/terms') }}">obchodní podmínky</a>).
</p>

<h2>Jak o vrácení požádat</h2>
<ul>
    <li>Žádost podejte do 14 dnů od platby na <a href="https://paddle.net" target="_blank" rel="noopener">paddle.net</a>
        nebo přes odkaz v e-mailu s dokladem o platbě.</li>
    <li>Paddle posuzuje každou žádost jednotlivě. Vrácení odmítne, pokud jde o podvod nebo zneužití.</li>
</ul>

<h2>Odstoupení spotřebitele</h2>
<p>
    Spotřebitelé v EU (a v dalších zemích, kde to stanoví zákon) mají právo odstoupit od smlouvy uzavřené na dálku
    do 14 dnů. Toto právo se nevztahuje na další platby již běžícího předplatného. Kdy právo odstoupit zaniká
    (např. když služba na vaši výslovnou žádost začala hned), uvádějí pravidla Paddle.
</p>

<h2>Zrušení předplatného</h2>
<p>
    Předplatné můžete kdykoli zrušit v aplikaci (Předplatné). Zrušení platí ke konci zaplaceného období: do té doby
    tarif trvá a další platba se už nestrhne. Samotné zrušení vrácení peněz za zbytek období neznamená.
</p>

